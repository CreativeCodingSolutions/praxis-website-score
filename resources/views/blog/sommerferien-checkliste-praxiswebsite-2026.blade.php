        <div class="prose prose-lg max-w-none text-gray-700">
            <p class="text-lg leading-relaxed">Die Sommerferien nähern sich — und mit ihnen die schwierigste Zeit für Praxen. Urlaub, Vertretungen, weniger Personal. Aber: Patienten suchen weiterhin online. Wer im Sommer nicht gut aufgestellt ist, verliert wertvolle Neupatienten an besser vorbereitete Konkurrenten.</p>

            <p>Die gute Nachricht: Sie brauchen keinen teuren Relaunch. Mit diesen 10 Punkten auf unserer Sommerferien-Checkliste stellen Sie Ihre Praxiswebsite bis Juli fit — Schritt für Schritt, ohne Stress.</p>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Checkliste: 10 Punkte für Ihre Praxiswebsite</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">1. Vertretungsregelung sichtbar anzeigen</h3>
            <p>Das Wichtigste zuerst: Wenn Ihre Praxis in den Sommerferien eingeschränkt geöffnet hat oder eine Vertretung vergibt, muss das <strong>sofort</strong> auf der Website sichtbar sein.</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Banner auf der Startseite mit Hinweis „In der Woche vom [Datum] sind wir eingeschränkt geöffnet"</li>
                <li>Vertretungsdaten mit Telefonnummer</li>
                <li>Hinweis auf Notfallnummern</li>
            </ul>
            <p><strong>Quick-Win:</strong> Binden Sie eine Banner-Leiste ganz oben ein, die auf der <strong>gesamten</strong> Website sichtbar ist.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">2. Online-Buchung für den Herbst aktivieren</h3>
            <p>Die meisten Praxen machen den Fehler, Online-Buchungen während der Ferien zu pausieren. Gegenteil ist der Fall: Nutzen Sie die Zeit, um das System perfekt einzurichten.</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Testbuchungen durchführen lassen</li>
                <li>SMS/E-Mail-Erinnerungen konfigurieren</li>
                <li>Freie Herbsttermine freischalten (September–November)</li>
            </ul>
            <p><strong>Tipp:</strong> Patienten, die online buchen, haben eine 40% niedrigere No-Show-Rate, weil sie die Terminbestätigung direkt auf dem Handy haben.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">3. Ladegeschwindigkeit unter 2,5 Sekunden bringen</h3>
            <p>Google bewertet Seiten mit weniger als 2,5 Sekunden Ladezeit (LCP) positiv. Im Sommer suchen Patienten oft auch mobil von unterwegs — und hier zählt jeder Millisekunde.</p>
            <p><strong>Kostenlose Tools für den Quick-Check:</strong></p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li><a href="https://pagespeed.web.dev" class="text-indigo-600 hover:underline">Google PageSpeed Insights</a></li>
                <li><a href="https://gtmetrix.com" class="text-indigo-600 hover:underline">GTmetrix</a></li>
            </ul>
            <p><strong>Häufige Verlangsamungs-Faktoren:</strong></p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Unkomprimierte Bilder (vor allem Praxis-Fotos)</li>
                <li>Zusätzliche Plugins oder Tracking-Skripte</li>
                <li>Kein Caching aktiviert</li>
            </ul>
            <p>Ihr kostenloser Praxis Website Score zeigt Ihnen in 30 Sekunden, wo der Schuh drückt: <a href="/" class="text-indigo-600 hover:underline font-medium">Jetzt Website prüfen</a></p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">4. Google Business Profile auf Vordermann bringen</h3>
            <p>Im Sommer verändern sich Suchverhalten und Öffnungszeiten. Aktualisieren Sie Ihr Google Business Profile:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Aktuelle Öffnungszeiten (auch mit Hinweis auf Ferienzeiten)</li>
                <li>Ferien-spezielle Attribute: „Vorübergehend geöffnet" oder „Vertretungsversorgung"</li>
                <li>Aktuelle Sommer-Fotos hochladen</li>
                <li>Google-Post erstellen mit Herbst-Angebot</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">5. Bewertungen gezielt sammeln</h3>
            <p>Im Sommer hat Zeit mehr Leute Zeit für Google-Bewertungen — nutzen Sie das:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Freundliche Erinnerung im Wartezimmer-Ausgang</li>
                <li>QR-Code zum Bewertungslink direkt an der Rezeption</li>
                <li>E-Mail nach dem Termin mit Bewertungshinweis</li>
            </ul>
            <p><strong>Ziel:</strong> Bis Ende August 5+ neue Google-Bewertungen sammeln. Das verbessert Ihr Ranking in der lokalen Suche sofort nachhaltig.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">6. Patienten-FAQ-Bereich ausbauen</h3>
            <p>Viele Patienten googeln im Sommer nach Symptomen und suchen erst dann eine Praxis. Wenn Ihre Website gute Antworten bietet, werden Sie gefunden:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>„Was kostet ein Ersttermin ohne Überweisung?"</li>
                <li>„Wartezeit in den Sommerferien?"</li>
                <li>„Nehmen Sie neue Patienten auf?"</li>
                <li>„Notfallzeiten und Vertretung?"</li>
            </ul>
            <p><strong>SEO-Bonus:</strong> Jede gut beantwortete Frage ist eine Chance, bei Google Featured Snippets (Position 0) aufzutauchen.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">7. Mobile Darstellung testen</h3>
            <p>Über 70% aller Praxis-Websites werden mobil besucht. Prüfen Sie:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Ist die Telefonnummer mit nur einem Klick wählbar?</li>
                <li>Läuft die Navigation auch auf dem Smartphone flüssig?</li>
                <li>Sind die Buttons groß genug (mindestens 48px)?</li>
                <li>Ist die Schrift ohne Zoomen lesbar?</li>
            </ul>
            <p><strong>Quick-Test:</strong> Nehmen Sie Ihr eigenes Smartphone und durchlaufen Sie den Buchungsprozess. Wenn Sie sich irgendwo ärgern — Ihre Patienten auch.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">8. Cookie-Consent und Datenschutz aktuell halten</h3>
            <p>Die Datenschutzbehörden haben im letzten Jahr erneut auf Consent-basierte Cookie-Banner geprüft. Auch wenn Ihre Praxis keine kommerziellen Cookies nutzt:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Datenschutzerklärung auf dem aktuellen Stand?</li>
                <li>Cookie-Banner zeigt korrekte Optionen?</li>
                <li>Impressum vollständig (Handelsregister, USt-IdNr., Verantwortlicher)?</li>
            </ul>
            <p><strong>Risiko:</strong> Negative Urteile können existenziell sein. Datenschutz ist kein Marketing-Thema — aber ein Vertrauenssignal.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">9. Content für Herbst vorbereiten</h3>
            <p>Denken Sie jetzt bereits an September:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Blog-Beitrag „Impfungen und Vorsorge für den Herbst"</li>
                <li>Neue Terminkalender-Herbstplanung</li>
                <li>Eventuell neue Behandlungsmethoden bewerben</li>
                <li>Mitarbeiter-Stellenanzeigen (wegen Fachkräftemangel wichtig)</li>
            </ul>
            <p><strong>Vorteil:</strong> Google indexiert frische Inhalte mit Verzögerung. Wer jetzt publiziert, rankt im September.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">10. Praxis Website Score kostenlos prüfen lassen</h3>
            <p>Am wichtigsten: Wissen Sie überhaupt, wo Ihre Website steht?</p>
            <p>Unser <strong>Praxis Website Score</strong> prüft in <strong>30 Sekunden</strong>:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Ladegeschwindigkeit (Mobile + Desktop)</li>
                <li>Google-Sichtbarkeit und SEO-Faktoren</li>
                <li>Mobile Darstellung</li>
                <li>DSGVO-Checkliste</li>
                <li>Benchmark gegen andere Praxen</li>
            </ul>
            <p>Kostenlos, kein Abo, kein Risiko — und Sie erhalten eine klare Liste mit Verbesserungsideen, die Sie sofort umsetzen können.</p>
