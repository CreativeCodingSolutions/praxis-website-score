            <p>Die Realität: 78% der Praxiswebsites im DACH-Raum laden auf dem Handy zu langsam. 65% haben keine klare Aufforderung zum Anrufen. 52% sind bei Google nicht auf der ersten Seite.</p>

            <p>Für Zahnarztpraxen ist das besonders kritisch: Patienten wählen oft den Zahnarzt, der am einfachsten zu finden und zu kontaktieren ist.</p>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Was eine gute Zahnarzt-Website enthalten muss</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">1. Kontakt-Info prominent — nicht versteckt</h3>
            <p>Ihre Telefonnummer muss <strong>ohne Scrollen</strong> sichtbar sein. Auf dem Handy als klickbarer Link, der sofort wählt.</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li><strong>Fehler:</strong> Telefonnummer nur im Impressum oder im Footer.</li>
                <li><strong>Lösung:</strong> Sticky Header mit Telefon-Button + Online-Terminbuchung.</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">2. Leistungsbereich klar kommuniziert</h3>
            <p>Patienten wollen wissen: Behandeln Sie Prophylaxe? Implantate? Bleaching? Kinderzahnheilkunde?</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li><strong>Fehler:</strong> Generische Liste „Unsere Leistungen" ohne Erklärungen.</li>
                <li><strong>Lösung:</strong> 3-5 Kernleistungen mit je 2 Sätzen + Bild — mehr braucht keiner.</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">3. Online-Terminbuchung</h3>
            <p>Das ist 2026 kein Nice-to-have mehr, sondern Erwartungshaltung. 64% der Patienten bevorzugen Online-Buchung gegenüber Telefonanrufen.</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li><strong>Fehler:</strong> „Rufen Sie uns an zur Terminvereinbarung" als einzige Option.</li>
                <li><strong>Lösung:</strong> Buchungs-Widget direkt auf der Startseite integriert.</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">4. Social Proof: Bewertungen sichtbar</h3>
            <p>Google-Bewertungen sind die stärkste Vertrauenswährung für Zahnärzte. 4,2 Sterne oder besser = 63% eher gewählt als 3,8 Sterne.</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li><strong>Fehler:</strong> Keine Bewertungs-Integration auf der Website.</li>
                <li><strong>Lösung:</strong> Top 3-5 Google-Reviews auf der Startseite einbinden (automatisch aktualisiert).</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">5. DSGVO-Konform — vom ersten Tag</h3>
            <p>Als Arztpraxis haben Sie besondere Pflichten: Datenschutzerklärung, Cookie-Einwilligung, SSL-Zertifikat, sichere Patienten-Formulare.</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li><strong>Fehler:</strong> Datenschutzerklärung kopiert von irgendwo, Cookie-Banner fehlt.</li>
                <li><strong>Lösung:</strong> DSGVO-konforme Basis inkl. Consent-Management ab Tag 1.</li>
            </ul>

