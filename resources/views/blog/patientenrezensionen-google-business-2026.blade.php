        <div class="prose prose-lg max-w-none text-gray-700">
            <p class="text-lg leading-relaxed">93% der Patienten lesen online Bewertungen, bevor sie eine Praxis auswählen (Google, 2025). Trotzdem haben 62% der deutschen Arztpraxen weniger als 10 Google-Bewertungen — oder gar keine.</p>

            <p>Das ist ein riesiges Potenzial. Und es ist kostenlos.</p>

            <p>In diesem Post zeigen wir Ihnen, wie Sie systematisch mehr und bessere Bewertungen sammeln — ohne DSGVO-Verstoß und ohne teure Tools.</p>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Warum Google-Bewertungen Ihr wichtigstes Marketing-Tool sind</h2>

            <p>Google-Bewertungen sind für Praxen das, was Kundenbewertungen für E-Shops sind: Vertrauenssignale, die direkt am Entscheidungspunkt wirken. Der Unterschied: Sie müssen nicht einmal einen Online-Shop betreiben — nur ein Google Business Profile.</p>

            <p><strong>Die Zahlen sprechen für sich:</strong></p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>93% der Patienten lesen Bewertungen vor der Praxisauswahl</li>
                <li>Praxen mit 20+ Bewertungen erhalten 3x mehr Klicks auf Google Maps</li>
                <li>Jeder zusätzliche Stern im Durchschnitt erhöht die Klickrate um 15%</li>
                <li>47% der Patienten würden eine Praxis mit weniger als 4 Sternen meiden</li>
            </ul>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Die 5 größten Fehler bei Google-Bewertungen</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">1. Nie aktiv nach Bewertungen fragen</h3>
            <p>Die meisten Praxen warten darauf, dass Patienten von selbst eine Bewertung schreiben. Das passiert selten. <strong>Lösung:</strong> Fragen Sie aktiv — aber richtig. Nach dem Termin, wenn die Erfahrung frisch ist und der Patient zufrieden war.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">2. Bewertungen auf der Website ignorieren</h3>
            <p>Sie haben 47 Google-Bewertungen mit 4,8 Sternen? Zeigen Sie das! <strong>Lösung:</strong> Google-Bewertungen live auf der Praxis-Website einbinden. Das erhöht die Conversion-Rate um 15-25%.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">3. Kein Google Business Profile</h3>
            <p>Ohne GBP tauchen Sie nicht in der lokalen Suche auf. Punkt. <strong>Lösung:</strong> Profil anlegen, verifizieren, optimieren. Kosten: 0€. Zeit: 15 Minuten.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">4. Negative Bewertungen ignorieren</h3>
            <p>Jede negative Bewertung ist eine Chance. Wer professionell antwortet, gewinnt mehr Vertrauen als wer nur 5-Sterne hat. <strong>Lösung:</strong> Innerhalb 24h antworten, empathisch und lösungsorientiert.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">5. Keine Struktur im Bewertungsmanagement</h3>
            <p>Wer sporadisch mal nachfragt, kommt nicht weit. <strong>Lösung:</strong> System etablieren — z.B. nach jedem positiven Besuch automatisch eine freundliche Erinnerung.</p>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Schritt-für-Schritt: Bewertungs-System für Ihre Praxis</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 1: Google Business Profile optimieren</h3>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Kategorie korrekt setzen (z.B. "Zahnarzt", nicht "Arzt")</li>
                <li>Öffnungszeiten aktuell halten</li>
                <li>Fotos hochladen (Praxis, Team, Empfangsbereich)</li>
                <li>Beschreibung mit relevanten Keywords (Zahnarzt + Stadt + Leistungen)</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 2: QR-Code im Wartezimmer</h3>
            <p>Erstellen Sie einen QR-Code, der direkt zur Google-Bewertungsseite führt. Drucken Sie ihn aus und platzieren Sie ihn an strategischen Stellen:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>An der Rezeption (beim Auschecken)</li>
                <li>Im Behandlungszimmer (auf dem Behandlungstisch)</li>
                <li>Auf der Rechnung/Rezept-Umschlag</li>
            </ul>
            <p><strong>Kosten:</strong> 0€. <strong>Effekt:</strong> 3-5x mehr Bewertungen pro Monat.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 3: E-Mail nach dem Besuch</h3>
            <p>24 Stunden nach dem Besuch: Eine kurze, freundliche E-Mail mit Link zur Google-Bewertungsseite.</p>
            <div class="bg-gray-50 border border-gray-200 rounded-lg p-4 my-4">
                <p class="text-sm text-gray-600 italic"><strong>Template:</strong></p>
                <p class="text-sm text-gray-600 mt-2">"Lieber [Name], vielen Dank, dass Sie uns besucht haben. Wir freuen uns, wenn Sie uns bei Google bewerten — das hilft anderen Patienten, uns zu finden. [Link]"</p>
            </div>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 4: Bewertungen auf der Website einbinden</h3>
            <p>Zeigen Sie Ihre besten Bewertungen live auf der Startseite. Das erhöht die Conversion-Rate um 15-25%. Plattformen wie Elfsight oder EmbedSocial bieten kostenlose Widgets an.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 5: Auf jede Bewertung antworten</h3>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li><strong>Positiv:</strong> Dank ausdrücken, persönlicher Bezug, Einladung für den nächsten Besuch</li>
                <li><strong>Negativ:</strong> Professionell, lösungsorientiert, empathisch — und wenn möglich offline klären</li>
            </ul>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">DSGVO-Hinweis: Was Sie nicht tun dürfen</h2>

            <div class="bg-red-50 border border-red-200 rounded-lg p-4 my-4">
                <p class="text-sm font-semibold text-red-800 mb-2">Verboten:</p>
                <ul class="list-disc list-inside space-y-1 text-sm text-red-700">
                    <li>Bewertungen kaufen oder falsche Bewertungen schreiben</li>
                    <li>Bewertungen belohnen (Gutscheine gegen 5 Sterne)</li>
                    <li>Bewertungen löschen lassen (außer rechtswidrig)</li>
                </ul>
            </div>

            <div class="bg-green-50 border border-green-200 rounded-lg p-4 my-4">
                <p class="text-sm font-semibold text-green-800 mb-2">Erlaubt:</p>
                <ul class="list-disc list-inside space-y-1 text-sm text-green-700">
                    <li>Aktiv nach ehrlichen Bewertungen fragen</li>
                    <li>QR-Code bereitstellen</li>
                    <li>E-Mail mit Bewertungslink senden (mit Einwilligung)</li>
                </ul>
