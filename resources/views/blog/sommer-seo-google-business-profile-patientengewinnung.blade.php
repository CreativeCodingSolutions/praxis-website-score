                        <li>"Neue Sprechstunden im August"</li>
                    </ul>
                </li>
                <li>[ ] Bild hinzufügen (Fassade, Team, Praxis)</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 4: Website-Check (4 Minuten)</h3>
            <ul class="list-disc list-inside space-y-1">
                <li>[ ] Mobile Ladegeschwindigkeit prüfen (PageSpeed Insights)</li>
                <li>[ ] Schema.org LocalBusiness prüfen</li>
                <li>[ ] GBP-Link auf der Website sichtbar?</li>
                <li>[ ] Klickbare Telefonnummer (mobil)</li>
            </ul>

