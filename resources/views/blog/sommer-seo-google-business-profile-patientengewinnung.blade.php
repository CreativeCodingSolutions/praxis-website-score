            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Die 3 größten Sommer-SEO-Fehler</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Fehler 1: Google Business Profile ignorieren</h3>
            <p>Seit dem Google Local Update 2025 sieht die lokale Ranking-Formel so aus:</p>

            <div class="bg-gray-900 text-green-400 rounded-lg p-4 my-4 font-mono text-sm">
                <p>Local Ranking Score =</p>
                <p>  GBP-Vollständigkeit (30%)</p>
                <p>  + Reviews & Rating (25%)</p>
                <p>  + Website-Relevanz + SEO (20%)</p>
                <p>  + Klickverhalten (15%)</p>
                <p>  + Zitate & Konsistenz (10%)</p>
            </div>

            <p>Ihre Website macht nur <strong>20%</strong> des Rankings aus. Das GBP macht <strong>55%</strong> (Vollständigkeit + Reviews).</p>

            <p><strong>Die meisten Praxen investieren 80% ihrer SEO-Zeit in die Website — und ignorieren den größten Hebel.</strong></p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Fehler 2: Veraltete Öffnungszeiten</h3>
            <p>Im Juli/August haben viele Praxen geänderte Öffnungszeiten:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Urlaubsvertretungen</li>
                <li>Reduzierte Sprechstunden</li>
                <li>Geschlossen in bestimmten Wochen</li>
            </ul>
            <p>Wenn diese Daten nicht im GBP aktualisiert sind, zeigt Google falsche Informationen — und bestraft Sie im Ranking.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Fehler 3: Keine neuen Bewertungen</h3>
            <p>Im Sommer generieren die meisten Praxen 40-60% weniger Google Reviews:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Weniger Patienten = weniger Gelegenheiten für Reviews</li>
                <li>Urlaubsvertretung = Patienten kennen das Team nicht</li>
                <li>Kein aktives Review-Management</li>
            </ul>
            <p><strong>Jeden Monat ohne neue Reviews = Ranking-Verlust.</strong></p>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Der 15-Minuten-Sommer-SEO-Check</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 1: GBP-Öffnungszeiten (3 Minuten)</h3>
            <ul class="list-disc list-inside space-y-1">
                <li>[ ] Aktuelle Öffnungszeiten im GBP prüfen</li>
                <li>[ ] Urlaubszeiten als "Zeitweise geschlossen" markieren</li>
                <li>[ ] Vertretungspraxis verlinken (falls vorhanden)</li>
                <li>[ ] Telefonnummer für Notfälle aktualisieren</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 2: Review-Generierung (5 Minuten)</h3>
            <ul class="list-disc list-inside space-y-1">
                <li>[ ] QR-Code am Empfang prüfen (ist er sichtbar?)</li>
                <li>[ ] SMS-Template für Review-Anfragen aktualisieren</li>
                <li>[ ] Letzte Google Review prüfen (wie alt?)</li>
                <li>[ ] Ziel: 3-5 neue Reviews diese Woche</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Schritt 3: Google Post (3 Minuten)</h3>
            <ul class="list-disc list-inside space-y-1">
                <li>[ ] Neue Google Post erstellen (Sommer-Thema)</li>
                <li>[ ] Empfohlene Themen:
                    <ul class="list-disc list-inside ml-4 mt-1">
