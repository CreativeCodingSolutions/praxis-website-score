            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Lead-Recherche-Strategie nach Praxistyp</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Neue Praxis (0-2 Jahre)</h3>
            <p>Fokus: Sichtbarkeit aufbauen. Google Business Profile, Jameda, erste Google Ads, Bewertungs-System. Budget: 200-500€/Monat.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Etablierte Praxis (2-10 Jahre)</h3>
            <p>Fokus: Optimierung und Skalierung. Content-Marketing, Empfehlungsnetzwerk, Doctolib, gezielte Google Ads. Budget: 500-1.500€/Monat.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Mehrpraxis / Kette</h3>
            <p>Fokus: Systematisierung und Automatisierung. CRM-System, zentrales Bewertungsmanagement, professionelle SEO, Social Media Team. Budget: 2.000€+/Monat.</p>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Die Lead-Recherche-Falle: Was Praxen falsch machen</h2>

            <ul class="list-disc list-inside space-y-2 mt-2">
                <li><strong>Keine Messbarkeit:</strong> Wer nicht trackt, woher Patienten kommen, kann nicht optimieren.</li>
                <li><strong>Zu viele Kanäle gleichzeitig:</strong> Lieber 2-3 Kanäle perfekt machen als 7 Kanäle mittelmäßig.</li>
                <li><strong>Kein Follow-Up:</strong> 60% der Leads gehen verloren, weil ninnerhalb von 24h geantwortet wird.</li>
                <li><strong>Website als Visitenkarte statt Lead-Generator:</strong> Ihre Website sollte Patienten konvertieren, nicht nur informieren.</li>
            </ul>

