            <p>Dieser Leitfaden zeigt Ihnen Schritt für Schritt, wie Sie als Arzt, Zahnarzt oder Therapeut einen nachhaltigen Lead-Aufbau aufbauen — ohne Agentur, ohne riesige Budgets, mit Methoden, die heute funktionieren.</p>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Was bedeutet Lead-Recherche für Praxen?</h2>

            <p>Ein "Lead" im Praxis-Kontext ist eine potenzielle Patientin oder ein potenzieller Patient, der Interesse an einer Behandlung zeigt. Lead-Recherche ist der Prozess, diese Personen systematisch zu identifizieren, anzusprache und in buchbare Termine umzuwandeln.</p>

            <p><strong>Die 3 Phasen der Lead-Recherche:</strong></p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li><strong>Attraktion:</strong> Potenzielle Patienten werden auf Ihre Praxis aufmerksam</li>
                <li><strong>Interaktion:</strong> Sie kontaktieren Sie (Anruf, Buchung, Kontaktformular)</li>
                <li><strong>Konversion:</strong> Aus dem Lead wird ein buchbarer Termin</li>
            </ul>

            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Die 7 effektivsten Lead-Recherche-Methoden für Praxen</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">1. Lokale SEO — Der nachhaltigste Lead-Kanal</h3>
            <p>Patienten suchen bei Google nach "Zahnarzt in [Stadt]" oder "Physio [Stadt]". Wer dort in den Top 3 auftaucht, bekommt 70% aller Klicks. Lokale SEO ist die Grundlage jeder Lead-Recherche-Strategie.</p>
            <p><strong>Quick-Wins:</strong> Google Business Profile optimieren, lokale Keywords auf der Website, NAP-Konsistenz (Name, Adresse, Telefon) über alle Plattformen.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">2. Bewertungsmanagement als Lead-Magnet</h3>
            <p>93% der Patienten lesen Bewertungen vor der Praxisauswahl. Praxen mit 20+ Google-Bewertungen und 4,5+ Sternen erhalten 3x mehr Anfragen als solche ohne Bewertungen.</p>

            <div class="bg-green-50 border border-green-200 rounded-lg p-4 my-6">
                <p class="text-green-800 text-sm"><strong>✅ Bewertungs-System etablieren:</strong></p>
                <ul class="list-disc list-inside space-y-1 text-sm text-green-700 mt-2">
                    <li>QR-Code an der Rezeption zur Google-Bewertung</li>
                    <li>E-Mail 24h nach dem Termin mit Bewertungslink</li>
                    <li>Auf jede Bewertung innerhalb von 48h antworten</li>
                </ul>
            </div>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">3. Jameda & Doctolib — Die Patienten-Börsen</h3>
            <p>Jameda ist mit 16M Monatsbesuchern die größte Arztsuchplattform in Deutschland. Doctolib ermöglicht Online-Buchung und reduziert Absagen um 40%. Beide Plattformen sind Lead-Generatoren und Vertrauenssignale zugleich.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">4. Content-Marketing mit Patienten-Fokus</h3>
            <p>Blogbeiträge, die echte Patientenfragen beantworten, generieren organische Leads über Google. Beispiele:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>"Was kostet eine Zahnimplantat-Behandlung in [Stadt]?"</li>
                <li>"Wann zum Physiotherapeuten? 5 Warnzeichen"</li>
                <li>"Kassenleistung oder IGeL? — Was Sie bei [Behandlung] wissen sollten"</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">5. Google Ads für lokale Suchanfragen</h3>
            <p>Mit einem Budget von 300-500€/Monat können Sie gezielt Patienten erreichen, die gerade nach Ihrer Leistung suchen. Wichtig: Landingpages mit klarem Call-to-Action (Telefonnummer, Kontaktformular, Online-Buchung).</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">6. Empfehlungsnetzwerk mit Kollegen</h3>
            <p>67% der Patienten kommen durch Empfehlungen. Bauen Sie aktives Netzwerk auf:</p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>Hausärzte in der Umgebung (für Fachärzte)</li>
                <li>Physiotherapeuten (für Orthopäden)</li>
                <li>Apotheken (für alle Praxen)</li>
                <li>Betriebsärzte (für alle Fachrichtungen)</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">7. Social Media für Praxen</h3>
            <p>Instagram und Facebook sind für Praxen unterschätzte Lead-Quellen. Vorher-Nachher-Bilder (mit Einwilligung), Patientenstimmen und Einblicke in den Praxisalltag bauen Vertrauen auf. 41% der 18-45-Jährigen suchen Praxen über Social Media.</p>

